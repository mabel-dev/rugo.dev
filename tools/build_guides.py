class GuideError(Exception):
    pass


def esc(text):
    return html.escape(str(text), quote=True)


# ── loading ─────────────────────────────────────────────────────────────────


def split_front_matter(path, text):
    m = re.match(r"\A---\s*\n(.*?)\n---\s*\n(.*)\Z", text, re.S)
    if not m:
        raise GuideError(f"{path.name}: missing `---` front matter block")
    meta = yaml.safe_load(m.group(1)) or {}
    if not isinstance(meta, dict):
        raise GuideError(f"{path.name}: front matter must be a mapping")
    return meta, m.group(2)


def as_date(path, key, value):
    if isinstance(value, datetime.datetime):
        return value.date()
    if isinstance(value, datetime.date):
        return value
    try:
        return datetime.date.fromisoformat(str(value))
    except ValueError:
        raise GuideError(f"{path.name}: `{key}` must be YYYY-MM-DD, got {value!r}")


def load_guide(path):
    meta, body = split_front_matter(path, path.read_text(encoding="utf-8"))
    name = path.name
    for key in ("title", "summary", "formats", "verbs", "published"):
        if not meta.get(key):
            raise GuideError(f"{name}: front matter needs `{key}`")

    slug = path.stem
    if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", slug):
        raise GuideError(f"{name}: filename must be lowercase-hyphenated (it becomes the URL)")

    formats = meta["formats"] if isinstance(meta["formats"], list) else [meta["formats"]]
    for f in formats:
        if f not in FORMATS:
            raise GuideError(f"{name}: unknown format {f!r} (known: {', '.join(FORMATS)})")

    verbs = meta["verbs"] if isinstance(meta["verbs"], list) else [meta["verbs"]]
    for v in verbs:
        if v not in VERBS:
            raise GuideError(f"{name}: unknown rugo verb {v!r} (known: {', '.join(sorted(VERBS))})")

    kind = meta.get("kind")
    if kind is not None and kind not in KINDS:
        raise GuideError(f"{name}: unknown kind {kind!r} (known: {', '.join(KINDS)})")

    summary = " ".join(str(meta["summary"]).split())
    description = " ".join(str(meta.get("description") or summary).split())
    title = " ".join(str(meta["title"]).split())
    if len(description) > 160:
        print(f"warning: {name}: description is {len(description)} chars; search results cut at ~160")
    if len(title) > 60:
        print(f"warning: {name}: title is {len(title)} chars; search results cut at ~60")

    words = len(re.findall(r"\w+", body)) + len(re.findall(r"\w+", str(meta.get("try_it", ""))))
    reading_time = meta.get("reading_time") or max(1, math.ceil(words / WORDS_PER_MINUTE))

    published = as_date(path, "published", meta["published"])
    updated = as_date(path, "updated", meta["updated"]) if meta.get("updated") else published

    return {
        "slug": slug,
        "title": title,
        "summary": summary,
        "description": description,
        "formats": formats,
        "verbs": verbs,
        "kind": kind,
        "reading_time": int(reading_time),
        "published": published,
        "updated": updated,
        "verified_with": str(meta["verified_with"]) if meta.get("verified_with") else None,
        "viewer": bool(meta.get("viewer", False)),
        "try_it": str(meta["try_it"]).strip("\n") if meta.get("try_it") else None,
        "body": body,
        "draft": bool(meta.get("draft", False)),
    }


def load_all():
    guides = []
    for path in sorted(SRC.glob("*.md")):
        if path.name.startswith("_"):
            continue
        g = load_guide(path)
        if not g["draft"]:
            guides.append(g)
    # newest first, then A-Z, so the order never depends on filenames
    guides.sort(key=lambda g: (-g["published"].toordinal(), g["title"].lower()))
    return guides


# ── tabs ────────────────────────────────────────────────────────────────────


def build_tabs(guides):
    """All, then each format, then each kind. Tabs with no guides are left out, so a
    new format or kind shows up the moment its first guide is added."""
    tabs = [{"slug": "", "label": "All", "match": lambda g: True, "noun": ""}]
    for key, (label, slug) in FORMATS.items():
        tabs.append({"slug": slug, "label": label, "match": lambda g, k=key: k in g["formats"], "noun": label})
    for key, (label, slug) in KINDS.items():
        tabs.append({"slug": slug, "label": label, "match": lambda g, k=key: g["kind"] == k, "noun": label})
    for tab in tabs:
        tab["guides"] = [g for g in guides if tab["match"](g)]
        tab["count"] = len(tab["guides"])
    shown = [t for t in tabs if t["slug"] == "" or t["count"]]
    reserved = {t["slug"] for t in tabs}
    for g in guides:
        if g["slug"] in reserved:
            raise GuideError(f"{g['slug']}.md: filename collides with a filter-tab URL; rename it")
    return shown


def tab_url(tab):
    return "/guides/" + (tab["slug"] + "/" if tab["slug"] else "")


# ── markup ──────────────────────────────────────────────────────────────────


def head(title, description, canonical, og_type="website", extra=""):
    return f"""\
    <head>
        <meta charset="UTF-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1.0" />
        <title>{esc(title)}</title>
        <meta name="description" content="{esc(description)}" />
        <link rel="canonical" href="{esc(canonical)}" />
        <meta name="robots" content="index, follow, max-snippet:-1, max-image-preview:large" />
        <meta property="og:site_name" content="Rugo" />
        <meta property="og:type" content="{og_type}" />
        <meta property="og:title" content="{esc(title)}" />
        <meta property="og:description" content="{esc(description)}" />
        <meta property="og:url" content="{esc(canonical)}" />
        <meta name="twitter:card" content="summary" />
        <meta name="twitter:title" content="{esc(title)}" />
        <meta name="twitter:description" content="{esc(description)}" />
{extra}        <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
        <link rel="stylesheet" href="/blog.css" />
        <link rel="stylesheet" href="/guides.css" />
    </head>
"""


def ld_json(data):
    # `</` inside a script element would end it early
    return (
        '        <script type="application/ld+json">'
        + json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
        + "</script>\n"
    )


def format_tags(g):
    return "".join(f'<span class="tag">{esc(FORMATS[f][0])}</span>' for f in g["formats"])


def verb_chips(g):
    return "".join(f"<code>rugo {esc(v)}</code>" for v in g["verbs"])


def card(g):
    url = f"/guides/{g['slug']}/"
    return f"""\
                    <article class="guide-card">
                        <div class="guide-card-meta">
                            {format_tags(g)}
                            <span class="read-time">{g['reading_time']} min read</span>
                        </div>
                        <h2><a href="{url}">{esc(g['title'])}</a></h2>
                        <p class="guide-summary">{esc(g['summary'])}</p>
                        <p class="guide-verbs" aria-label="rugo commands used">{verb_chips(g)}</p>
                        <a class="guide-link" href="{url}">Read guide<span aria-hidden="true"> →</span></a>
                    </article>
"""


def tabs_nav(tabs, current):
    items = []
    for t in tabs:
        cur = ' aria-current="page"' if t is current else ""
        items.append(
            f'                    <li><a href="{tab_url(t)}"{cur}>{esc(t["label"])}'
            f' <span class="count">({t["count"]})</span></a></li>\n'
        )
    return (
        '                <nav class="guide-tabs" aria-label="Filter guides">\n'
        "                    <ul>\n" + "".join(items) + "                    </ul>\n"
        "                </nav>\n"
    )


def noun_phrase(tab):
    n = tab["count"]
    return f"{n} guide" + ("" if n == 1 else "s")


def index_page(tab, tabs):
    if tab["slug"] == "":
        title = "Guides — rugo"
        h1 = "Guides"
        intro = (
            "Short, runnable guides to reading, inspecting and converting Parquet, "
            "JSONL, CSV and Avro with the rugo command line. Every command runs as written."
        )
        description = (
            f"{noun_phrase(tab)} on reading, inspecting and converting Parquet, JSONL, CSV and Avro "
            "files with the rugo CLI. No PyArrow, no pandas."
        )
    elif tab["slug"] in {s for _, s in KINDS.values()}:
        title = f"{tab['label']} — rugo guides"
        h1 = tab["label"]
        intro = f"{noun_phrase(tab).capitalize()} in the {tab['label'].lower()} collection."
        description = f"{noun_phrase(tab).capitalize()}: rugo {tab['label'].lower()} for Parquet, JSONL, CSV and Avro files."
    else:
        title = f"{tab['label']} guides — rugo"
        h1 = f"{tab['label']} guides"
        intro = f"Reading, inspecting and converting {tab['label']} files with the rugo command line."
        description = f"{noun_phrase(tab).capitalize()} on working with {tab['label']} files using the rugo CLI. No PyArrow, no pandas."
    canonical = SITE + tab_url(tab)

    ld = ld_json(
        {
            "@context": "https://schema.org",
            "@type": "CollectionPage",
            "name": h1,
            "description": description,
            "url": canonical,
            "isPartOf": {"@type": "WebSite", "name": "Rugo", "url": SITE + "/"},
            "mainEntity": {
                "@type": "ItemList",
                "numberOfItems": tab["count"],
                "itemListElement": [
                    {"@type": "ListItem", "position": i, "url": f"{SITE}/guides/{g['slug']}/", "name": g["title"]}
                    for i, g in enumerate(tab["guides"], 1)
                ],
            },
        }
    )
    cards = "".join(card(g) for g in tab["guides"])
    return (
        "<!doctype html>\n" + GENERATED + '\n<html lang="en">\n'
        + head(title, description, canonical, extra=ld)
        + "    <body>\n"
        + NAV.format(guides_current=' aria-current="page"')
        + f"""
        <main class="guides-hub">
            <div class="container wide">
                <h1>{esc(h1)}</h1>
                <p class="listing-intro">{esc(intro)}</p>
"""
        + tabs_nav(tabs, tab)
        + f"""
                <div class="guide-grid">
{cards}                </div>
            </div>
        </main>

"""
        + FOOTER
        + "    </body>\n</html>\n"
    )


MD_EXTENSIONS = ["fenced_code", "tables", "sane_lists", "toc"]


def render_body(g):
    out = markdown.markdown(g["body"], extensions=MD_EXTENSIONS, output_format="html")
    if re.search(r"<h1[ >]", out):
        raise GuideError(f"{g['slug']}.md: don't use `# ` in the body; the title comes from front matter")
    # a fence tagged `output` is the expected output of the command above it
    out = out.replace('<pre><code class="language-output">', '<pre class="output"><code>')
    out = re.sub(r"<table>.*?</table>", lambda m: f'<div class="table-scroll">{m.group(0)}</div>', out, flags=re.S)
    return out


def try_it_block(g):
    if not g["try_it"]:
        return ""
    return f"""\
                <section class="try-it" aria-labelledby="try-it">
                    <h2 id="try-it">Try it</h2>
                    <pre><code class="language-bash">{esc(g['try_it'])}</code></pre>
                </section>
"""


def viewer_block(g):
    if not (VIEWER_URL and g["viewer"]):
        return ""
    return f"""\
                <p class="viewer-link"><a href="{esc(VIEWER_URL)}">Open a file in the browser viewer →</a></p>
"""


def guide_page(g, tabs):
    url = f"/guides/{g['slug']}/"
    canonical = SITE + url
    first_tab = next(t for t in tabs if t["slug"] and t["match"](g)) if g["formats"] else None
    crumb_tab = first_tab or tabs[0]
    ld = ld_json(
        {
            "@context": "https://schema.org",
            "@type": "TechArticle",
            "headline": g["title"],
            "description": g["description"],
            "url": canonical,
            "mainEntityOfPage": canonical,
            "datePublished": g["published"].isoformat(),
            "dateModified": g["updated"].isoformat(),
            "inLanguage": "en",
            "keywords": ", ".join([FORMATS[f][0] for f in g["formats"]] + [f"rugo {v}" for v in g["verbs"]]),
            "author": {"@type": "Organization", "name": "Rugo", "url": SITE + "/"},
            "publisher": {"@type": "Organization", "name": "Rugo", "url": SITE + "/"},
        }
    ) + ld_json(
        {
            "@context": "https://schema.org",
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "Guides", "item": SITE + "/guides/"},
                {"@type": "ListItem", "position": 2, "name": crumb_tab["label"], "item": SITE + tab_url(crumb_tab)},
                {"@type": "ListItem", "position": 3, "name": g["title"], "item": canonical},
            ],
        }
    )
    extra = (
        f'        <meta property="article:published_time" content="{g["published"].isoformat()}" />\n'
        f'        <meta property="article:modified_time" content="{g["updated"].isoformat()}" />\n'
        + "".join(f'        <meta property="article:tag" content="{esc(FORMATS[f][0])}" />\n' for f in g["formats"])
        + ld
    )
    verified = (
        f'<p class="verified">Commands checked against rugo {esc(g["verified_with"])}.</p>'
        if g["verified_with"]
        else ""
    )
    return (
        "<!doctype html>\n" + GENERATED + '\n<html lang="en">\n'
        + head(f"{g['title']} — rugo guides", g["description"], canonical, og_type="article", extra=extra)
        + "    <body>\n"
        + NAV.format(guides_current=' aria-current="page"')
        + f"""
        <article class="guide">
            <div class="container">
                <p class="breadcrumb"><a href="/guides/">Guides</a> <span aria-hidden="true">/</span> <a href="{tab_url(crumb_tab)}">{esc(crumb_tab['label'])}</a></p>
                <header class="post-header">
                    <h1>{esc(g['title'])}</h1>
                    <p class="post-meta">
                        {format_tags(g)}
                        <span class="sep">·</span> {g['reading_time']} min read
                        <span class="sep">·</span> Updated <time datetime="{g['updated'].isoformat()}">{g['updated'].day} {g['updated']:%B %Y}</time>
                    </p>
                    <p class="guide-verbs" aria-label="rugo commands used">{verb_chips(g)}</p>
                </header>

"""
        + try_it_block(g)
        + viewer_block(g)
        + "                <div class=\"guide-body\">\n"
        + render_body(g)
        + f"""
                </div>
                {verified}
                <p class="back"><a href="/guides/">← All guides</a></p>
            </div>
        </article>

"""
        + FOOTER
        + COPY_SCRIPT
        + "    </body>\n</html>\n"
    )


# ── build ───────────────────────────────────────────────────────────────────


def render_all():
    """Return {relative path under docs/guides: file text}."""
    guides = load_all()
    tabs = build_tabs(guides)
    files = {}
    for tab in tabs:
        files[(tab["slug"] + "/" if tab["slug"] else "") + "index.html"] = index_page(tab, tabs)
    for g in guides:
        files[f"{g['slug']}/index.html"] = guide_page(g, tabs)
    return files, tabs


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if docs/guides/ is out of date")
    args = ap.parse_args()

    try:
        files, tabs = render_all()
    except GuideError as e:
        sys.exit(f"error: {e}")

    if args.check:
        stale = []
        for rel, text in files.items():
            p = OUT / rel
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                stale.append(rel)
        extra = sorted(str(p.relative_to(OUT)) for p in OUT.rglob("*.html") if str(p.relative_to(OUT)) not in files) if OUT.exists() else []
        if stale or extra:
            for rel in stale:
                print(f"stale:  docs/guides/{rel}")
            for rel in extra:
                print(f"orphan: docs/guides/{rel}")
            sys.exit("docs/guides/ is out of date; run: python3 tools/build_guides.py")
        print("docs/guides/ is up to date")
        return

    if OUT.exists():
        shutil.rmtree(OUT)
    for rel, text in files.items():
        p = OUT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} pages to docs/guides/")
    for t in tabs:
        print(f"  {t['label']} ({t['count']})  {tab_url(t)}")


if __name__ == "__main__":
    main()
