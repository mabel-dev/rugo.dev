"""Build the rugo.dev guides hub: docs/guides/**.

    python3 tools/build_guides.py            # regenerate docs/guides/
    python3 tools/build_guides.py --check    # exit 1 if docs/guides/ is stale

Adding a guide means adding ONE Markdown file to guides/ (see guides/_template.md).
Run this script and commit the result: the hub, every filter tab, the counts and
the guide page itself are all generated, so nothing else is edited by hand.

Needs `pip install markdown pyyaml`. docs/guides/ is wholly generated; the script
deletes and rewrites it, so never edit files in there.

Layout produced (every tab is a plain static page, so filtering needs no JavaScript):

    /guides/                 All
    /guides/parquet/         Parquet          (one per format that has guides)
    /guides/comparisons/     Comparisons
    /guides/<slug>/          one page per guide
"""
import argparse
import datetime
import html
import json
import math
import re
import shutil
import sys
from pathlib import Path

import markdown
import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "guides"
OUT = ROOT / "docs" / "guides"
SITE = "https://rugo.dev"
GENERATED = "<!-- Generated by tools/build_guides.py from guides/*.md. Do not edit. -->"

# The browser viewer (RUGO-2) does not exist yet. When it ships, set its URL here and
# every guide with `viewer: true` in its front matter gains an "Open in the viewer"
# link. Until then the link is not rendered anywhere.
VIEWER_URL = None

# Formats rugo reads. Key = value used in a guide's `formats:` front matter.
# CLI formats are parquet/csv/jsonl/avro (rugo convert/split --format). ORC is read-only
# through the Python API (`from rugo import orc`), so it has no CLI verbs.
FORMATS = {
    "parquet": ("Parquet", "parquet"),
    "jsonl": ("JSON/JSONL", "jsonl"),
    "csv": ("CSV", "csv"),
    "avro": ("Avro", "avro"),
    "orc": ("ORC", "orc"),
}
# Values for `kind:` front matter -> (tab label, url slug)
KINDS = {
    "comparison": ("Comparisons", "comparisons"),
    "workflow": ("Workflows", "workflows"),
}
# Every subcommand of the rugo CLI. A typo in a guide's `verbs:` fails the build.
VERBS = {
    "info", "schema", "columns", "count", "preview", "head", "describe", "stats",
    "inspect", "diff", "convert", "merge", "split",
}
WORDS_PER_MINUTE = 180  # prose and code together; code reads slower than prose

NAV = """\
        <nav>
            <a class="nav-logo" href="/index.html">ru<span>go</span></a>
            <div class="nav-links">
                <a href="/index.html">Home</a>
                <a href="/guides/"{guides_current}>Guides</a>
                <a href="/blog/index.html">Blog</a>
                <a href="https://github.com/mabel-dev/opteryx-core/tree/main/rugo"
                    >Docs</a
                >
            </div>
        </nav>
"""

FOOTER = """\
        <footer>
            <div class="container">
                <span>rugo — Parquet, CSV, JSONL and Avro without PyArrow.</span>
                <a href="https://github.com/mabel-dev/opteryx-core/tree/main/rugo">Source on GitHub</a>
            </div>
        </footer>
"""

